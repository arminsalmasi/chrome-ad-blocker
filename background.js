// ShieldBlock service worker.
//
// storage.local is the single source of truth. Every relevant change runs one
// serialized sync that reconciles:
//   1. static DNR rulesets (enabled/disabled)
//   2. the dynamic allowlist rule
//   3. registered content scripts (cosmetic CSS + MAIN-world scriptlets)

const STATIC_RULESETS = ["ruleset_ads", "ruleset_trackers", "ruleset_cookies"];

const DEFAULTS = {
  masterEnabled: true,
  ruleset_ads: true,
  ruleset_trackers: true,
  ruleset_cookies: true,
  cosmeticEnabled: true,
  allowlistedDomains: []
};
const SETTING_KEYS = Object.keys(DEFAULTS);
const LEGACY_KEYS = ["allowlistRuleMap", "nextDynamicRuleId"];

const ALLOWLIST_RULE_ID = 1;
const ALLOWLIST_PRIORITY = 100; // above every static rule (priority 1)

const CONTENT_SCRIPT_IDS = {
  cosmetic: "sb-cosmetic",
  adStubs: "sb-ad-stubs",
  trackerStubs: "sb-tracker-stubs"
};
const PAGE_MATCHES = ["http://*/*", "https://*/*"];
const SCRIPT_ID_PREFIX = "sb-";
const SITE_COSMETIC_INDEX = "content/cosmetic_sites/index.json";

// Per-site cosmetic buckets ({file, matches}[]) generated by build_cosmetics.py.
let siteCosmeticIndex = null;
async function loadSiteCosmeticIndex() {
  if (!siteCosmeticIndex) {
    try {
      const res = await fetch(chrome.runtime.getURL(SITE_COSMETIC_INDEX));
      siteCosmeticIndex = res.ok ? await res.json() : [];
    } catch (_) {
      siteCosmeticIndex = [];
    }
  }
  return siteCosmeticIndex;
}

// Keep in sync with popup/popup.js.
const IPV4_REGEX = /^(?:(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)\.){3}(?:25[0-5]|2[0-4]\d|1\d\d|[1-9]?\d)$/;
// Last label must contain a letter (rejects "foo.123", "999.999.999.999").
const HOSTNAME_REGEX = /^(?=.{1,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)*(?=[a-z0-9-]*[a-z])[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;

const isValidAllowlistEntry = (d) =>
  typeof d === "string" && (IPV4_REGEX.test(d) || HOSTNAME_REGEX.test(d));

// "*.example.com" in a match pattern covers example.com and all subdomains,
// matching DNR requestDomains semantics. IPs cannot take a "*." prefix.
const excludePatternFor = (d) => (IPV4_REGEX.test(d) ? `*://${d}/*` : `*://*.${d}/*`);

async function loadSettings() {
  const stored = await chrome.storage.local.get(SETTING_KEYS);
  const settings = { ...DEFAULTS };
  for (const key of SETTING_KEYS) {
    if (stored[key] !== undefined) settings[key] = stored[key];
  }
  settings.allowlistedDomains = (settings.allowlistedDomains || []).filter(isValidAllowlistEntry);
  return settings;
}

async function syncRulesets(s) {
  const enableRulesetIds = [];
  const disableRulesetIds = [];
  for (const id of STATIC_RULESETS) {
    (s.masterEnabled && s[id] ? enableRulesetIds : disableRulesetIds).push(id);
  }
  await chrome.declarativeNetRequest.updateEnabledRulesets({ enableRulesetIds, disableRulesetIds });
}

async function syncAllowlist(s) {
  const existing = await chrome.declarativeNetRequest.getDynamicRules();
  const addRules = [];
  if (s.masterEnabled && s.allowlistedDomains.length > 0) {
    // allowAllRequests on the top frame exempts the whole frame tree
    // (sub-resources and child frames) from block and modifyHeaders rules.
    addRules.push({
      id: ALLOWLIST_RULE_ID,
      priority: ALLOWLIST_PRIORITY,
      action: { type: "allowAllRequests" },
      condition: {
        requestDomains: s.allowlistedDomains,
        resourceTypes: ["main_frame"]
      }
    });
  }
  await chrome.declarativeNetRequest.updateDynamicRules({
    removeRuleIds: existing.map((r) => r.id),
    addRules
  });
}

async function syncContentScripts(s) {
  // Remove everything we registered (fixed scripts and per-site buckets).
  const registered = (await chrome.scripting.getRegisteredContentScripts())
    .filter((r) => r.id.startsWith(SCRIPT_ID_PREFIX));
  if (registered.length > 0) {
    await chrome.scripting.unregisterContentScripts({ ids: registered.map((r) => r.id) });
  }
  if (!s.masterEnabled) return;

  const base = {
    matches: PAGE_MATCHES,
    allFrames: true,
    // Also inject into about:blank / srcdoc / blob frames (common for ad
    // iframes), matched against the creating frame's origin.
    matchOriginAsFallback: true,
    runAt: "document_start",
    persistAcrossSessions: true
  };
  if (s.allowlistedDomains.length > 0) {
    base.excludeMatches = s.allowlistedDomains.map(excludePatternFor);
  }

  const scripts = [];
  if (s.cosmeticEnabled) {
    scripts.push({ ...base, id: CONTENT_SCRIPT_IDS.cosmetic, css: ["content/cosmetic.css"] });
    // Site-specific hiding: each bucket only runs on the sites it has rules for.
    // ISOLATED world (default), so pages can't see or tamper with it.
    (await loadSiteCosmeticIndex()).forEach((bucket, i) => {
      scripts.push({ ...base, id: `${SCRIPT_ID_PREFIX}cos-${i}`, matches: bucket.matches, js: [bucket.file] });
    });
  }
  if (s.ruleset_ads) {
    scripts.push({ ...base, id: CONTENT_SCRIPT_IDS.adStubs, js: ["content/scriptlets_ads.js"], world: "MAIN" });
  }
  if (s.ruleset_trackers) {
    scripts.push({ ...base, id: CONTENT_SCRIPT_IDS.trackerStubs, js: ["content/scriptlets_trackers.js"], world: "MAIN" });
  }
  // Register individually so one rejected script doesn't drop the others.
  const results = await Promise.allSettled(
    scripts.map((script) => chrome.scripting.registerContentScripts([script]))
  );
  const failed = results
    .map((r, i) => (r.status === "rejected" ? `${scripts[i].id}: ${r.reason}` : null))
    .filter(Boolean);
  if (failed.length > 0) throw new Error(`Content script registration failed: ${failed.join("; ")}`);
}

async function syncAll() {
  const s = await loadSettings();
  // Run each step independently so one failure doesn't leave the others stale.
  const results = await Promise.allSettled([syncRulesets(s), syncAllowlist(s), syncContentScripts(s)]);
  for (const r of results) {
    if (r.status === "rejected") console.error("ShieldBlock sync failed:", r.reason);
  }
}

// Serialize syncs: overlapping runs (install + startup, rapid popup toggles)
// would otherwise race on getDynamicRules/registerContentScripts.
let syncChain = Promise.resolve();
function scheduleSync() {
  syncChain = syncChain
    .then(syncAll)
    .catch((err) => console.error("ShieldBlock sync failed:", err));
  return syncChain;
}

// Reconcile on every service-worker start, so a worker killed mid-sync
// self-heals on its next wake instead of waiting for a settings change.
scheduleSync();

async function configureBadge() {
  // Native per-tab blocked-request count; works in packed (Web Store) builds,
  // unlike onRuleMatchedDebug, and survives service-worker restarts.
  await chrome.declarativeNetRequest.setExtensionActionOptions({ displayActionCountAsBadgeText: true });
  await chrome.action.setBadgeBackgroundColor({ color: "#d93838" });
}

chrome.runtime.onInstalled.addListener(async () => {
  const stored = await chrome.storage.local.get(SETTING_KEYS);
  const missing = {};
  for (const key of SETTING_KEYS) {
    if (stored[key] === undefined) missing[key] = DEFAULTS[key];
  }
  if (Object.keys(missing).length > 0) await chrome.storage.local.set(missing);
  await chrome.storage.local.remove(LEGACY_KEYS);
  await configureBadge().catch((err) => console.error("Badge setup failed:", err));
  await scheduleSync();
});

chrome.runtime.onStartup.addListener(async () => {
  await configureBadge().catch((err) => console.error("Badge setup failed:", err));
  await scheduleSync();
});

chrome.storage.onChanged.addListener((changes, area) => {
  if (area !== "local") return;
  if (SETTING_KEYS.some((key) => key in changes)) scheduleSync();
});

// ---------------------------------------------------------------------------
// Blocked-request log (for the popup's "View blocked requests" window).
//
// DNR doesn't expose blocked URLs to packed extensions, so we observe
// webRequest errors (read-only, non-blocking) and keep requests that failed
// with ERR_BLOCKED_BY_CLIENT. The log lives in chrome.storage.session: memory
// only, never synced or sent anywhere, cleared on navigation, tab close, and
// browser exit.
// ---------------------------------------------------------------------------
const BLOCKED_KEY_PREFIX = "blocked:";
const BLOCKED_MAX_PER_TAB = 1000;
const BLOCKED_URL_MAX = 600; // keeps the worst case well under storage.session's 10 MB
const BLOCKED_FLUSH_MS = 250;

const blockedLog = new Map(); // tabId -> { pageUrl, entries: [] }
const lastActivity = new Map(); // tabId -> ms, for evicting idle tabs under quota pressure
const dirtyTabs = new Set();
// Tabs that navigated or closed before the persisted log finished loading;
// their persisted entries are stale and must not be merged back.
const changedBeforeLoad = new Set();
let blockedLogLoaded = false;
let flushTimer = null;

const blockedLogReady = chrome.storage.session.get(null).then((all) => {
  for (const [key, value] of Object.entries(all)) {
    if (!key.startsWith(BLOCKED_KEY_PREFIX) || !value || !Array.isArray(value.entries)) continue;
    const tabId = Number(key.slice(BLOCKED_KEY_PREFIX.length));
    if (changedBeforeLoad.has(tabId)) continue;
    // Merge in case events were recorded before the load finished.
    const live = blockedLog.get(tabId);
    blockedLog.set(tabId, live ? { ...value, entries: value.entries.concat(live.entries) } : value);
  }
}).catch((err) => console.error("Blocked log load failed:", err))
  .finally(() => { blockedLogLoaded = true; changedBeforeLoad.clear(); });

function markDirty(tabId) {
  dirtyTabs.add(tabId);
  lastActivity.set(tabId, Date.now());
  if (!flushTimer) flushTimer = setTimeout(flushBlockedLog, BLOCKED_FLUSH_MS);
}

async function writeKey(key, value) {
  try {
    await chrome.storage.session.set({ [key]: value });
    return true;
  } catch (_) {
    // Likely the 10 MB session quota (shared by all tabs). Store a trimmed
    // copy; the in-memory log keeps everything.
    try {
      await chrome.storage.session.set({ [key]: { ...value, entries: value.entries.slice(-100) } });
      return true;
    } catch (err) {
      return false;
    }
  }
}

async function flushBlockedLog() {
  flushTimer = null;
  await blockedLogReady;
  const tabs = [...dirtyTabs];
  dirtyTabs.clear();
  const failed = [];
  for (const tabId of tabs) {
    const key = BLOCKED_KEY_PREFIX + tabId;
    const log = blockedLog.get(tabId);
    if (!log) {
      await chrome.storage.session.remove(key).catch(() => failed.push(tabId));
    } else if (!(await writeKey(key, log))) {
      failed.push(tabId);
    }
  }
  if (!failed.length) return;
  // Still over quota: drop the stored copies of the least recently active
  // other tabs (their in-memory logs stay until the worker restarts).
  const idle = [...lastActivity.entries()].filter(([id]) => !failed.includes(id))
    .sort((a, b) => a[1] - b[1]).slice(0, 5).map(([id]) => BLOCKED_KEY_PREFIX + id);
  await chrome.storage.session.remove(idle).catch(() => {});
  for (const tabId of failed) dirtyTabs.add(tabId); // retry on the next flush
  console.warn("Blocked log: session storage full; evicted idle tabs", idle);
}

function resetBlockedLog(tabId, pageUrl) {
  if (!blockedLogLoaded) changedBeforeLoad.add(tabId);
  blockedLog.set(tabId, { pageUrl: pageUrl || "", entries: [] });
  markDirty(tabId);
}

// Reset when the new page's response arrives (effectively when it commits), not
// when the navigation starts: a slow or cancelled click keeps the visible page's
// list intact. (webNavigation.onCommitted would need an extra install warning.)
chrome.webRequest.onResponseStarted.addListener(
  (details) => {
    if (details.tabId >= 0 && details.frameId === 0) resetBlockedLog(details.tabId, details.url);
  },
  { urls: ["<all_urls>"], types: ["main_frame"] }
);

chrome.webRequest.onErrorOccurred.addListener(
  (details) => {
    if (details.error !== "net::ERR_BLOCKED_BY_CLIENT" || details.tabId < 0) return;
    let host = "";
    try {
      const u = new URL(details.url);
      host = u.hostname || u.protocol.replace(/:$/, ""); // e.g. "blob" has no hostname
    } catch (_) {
      return;
    }
    let log = blockedLog.get(details.tabId);
    if (!log) {
      log = { pageUrl: "", entries: [] };
      blockedLog.set(details.tabId, log);
    }
    log.entries.push({
      url: details.url.slice(0, BLOCKED_URL_MAX),
      host,
      type: details.type,
      initiator: details.initiator || "",
      time: Math.round(details.timeStamp)
    });
    if (log.entries.length > BLOCKED_MAX_PER_TAB) log.entries.splice(0, log.entries.length - BLOCKED_MAX_PER_TAB);
    markDirty(details.tabId);
  },
  { urls: ["<all_urls>"] }
);

chrome.tabs.onRemoved.addListener((tabId) => {
  if (!blockedLogLoaded) changedBeforeLoad.add(tabId);
  blockedLog.delete(tabId);
  markDirty(tabId);
  lastActivity.delete(tabId);
});
