#!/usr/bin/env python3
"""Compile site-specific element-hiding rules (EasyList "domain##selector")
into per-site content scripts.

Only plain CSS selectors for explicit hostnames are kept. Procedural/extended
syntax (:has-text, :xpath, :upward, :style, +js scriptlets, ...), entity rules
(example.*), regex domains and generic rules are skipped. Exceptions
(domain#@#selector) remove the matching selector for that domain.

Hostnames are split into buckets; each bucket becomes content/cosmetic_sites/NN.js
holding only its hosts' selectors, and content/cosmetic_sites/index.json lists
each bucket's file and match patterns so background.js can register a bucket
only for the sites it covers.

Usage:
  build_cosmetics.py --dump SNAPSHOT.gz -i easylist        # refresh snapshot (network)
  build_cosmetics.py -i scripts/lists/easylist_cosmetic.txt.gz -o content/cosmetic_sites
"""

import argparse
import json
import os
import re
import shutil
import sys
import zlib

sys.path.insert(0, os.path.dirname(__file__))
from build_rules import DOMAIN_REGEX, dump_lines, fetch_or_read_file  # noqa: E402

BUCKETS = 64

# Extended/procedural syntax that is not valid CSS (or needs a script engine).
UNSUPPORTED_SELECTOR = re.compile(
    r":(-abp-|has-text|contains|xpath|upward|remove|style\(|matches-|min-text-length|watch-attr|"
    r"others|if\(|if-not|nth-ancestor|matches-path|matches-media)", re.I)
RULE_RE = re.compile(r"^([^#\s][^#]*?)(##|#@#)(.+)$")


def parse_cosmetic(line: str) -> tuple[list[str], str, bool] | None:
    """Return (hostnames, selector, is_exception) for a site-specific plain-CSS
    hiding rule, or None if the line is anything else."""
    line = line.strip()
    if not line or line.startswith(("!", "[")):
        return None
    m = RULE_RE.match(line)
    if not m:
        return None
    domains_part, sep, selector = m.groups()
    selector = selector.strip()
    if (not selector or selector.startswith(("+js", "^")) or "{" in selector or "}" in selector
            or UNSUPPORTED_SELECTOR.search(selector)):
        return None
    hosts = []
    for entry in domains_part.split(","):
        entry = entry.strip().lower()
        if entry.startswith("~"):
            continue  # negated domain: rule is a generic-with-exception for that host
        if DOMAIN_REGEX.match(entry):
            hosts.append(entry)
    if not hosts:
        return None
    return hosts, selector, sep == "#@#"


def compile_rules(lines) -> dict[str, list[str]]:
    hide: dict[str, set[str]] = {}
    allow: dict[str, set[str]] = {}
    for line in lines:
        parsed = parse_cosmetic(line)
        if not parsed:
            continue
        hosts, selector, is_exception = parsed
        target = allow if is_exception else hide
        for host in hosts:
            target.setdefault(host, set()).add(selector)
    return {h: sorted(sels - allow.get(h, set())) for h, sels in hide.items() if sels - allow.get(h, set())}


def bucket_of(host: str) -> int:
    return zlib.crc32(host.encode()) % BUCKETS


SCRIPT_TEMPLATE = """// Generated by scripts/build_cosmetics.py from EasyList. Do not edit by hand.
// Site-specific element hiding; see THIRD_PARTY_NOTICES.md for licensing.
(() => {{
  const RULES = {rules};
  const host = location.hostname;
  if (!host) return;
  const labels = host.split(".");
  const selectors = [];
  for (let i = 0; i < labels.length - 1; i++) {{
    const list = RULES[labels.slice(i).join(".")];
    if (list) selectors.push(...list);
  }}
  if (!selectors.length) return;
  // One rule per selector, so an unsupported selector only drops itself.
  const css = selectors.map((s) => s + "{{display:none!important}}").join("\\n");
  try {{
    const sheet = new CSSStyleSheet();
    sheet.replaceSync(css);
    document.adoptedStyleSheets = [...document.adoptedStyleSheets, sheet];
  }} catch (_) {{
    const style = document.createElement("style");
    style.textContent = css;
    (document.head || document.documentElement).appendChild(style);
  }}
}})();
"""


def write_buckets(rules: dict[str, list[str]], out_dir: str) -> dict:
    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)
    buckets: dict[int, dict[str, list[str]]] = {}
    for host, sels in rules.items():
        buckets.setdefault(bucket_of(host), {})[host] = sels
    index = []
    for n in sorted(buckets):
        data = dict(sorted(buckets[n].items()))
        name = f"{n:02d}.js"
        with open(os.path.join(out_dir, name), "w", encoding="utf-8") as f:
            f.write(SCRIPT_TEMPLATE.format(rules=json.dumps(data, separators=(",", ":"), ensure_ascii=False)))
        # "*://*.host/*" matches the host and all its subdomains.
        index.append({"file": f"{out_dir.rstrip('/')}/{name}", "matches": [f"*://*.{h}/*" for h in data]})
    with open(os.path.join(out_dir, "index.json"), "w", encoding="utf-8") as f:
        json.dump(index, f, indent=1)
        f.write("\n")
    return {"hosts": len(rules), "selectors": sum(map(len, rules.values())), "buckets": len(index)}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input", "-i", action="append", required=True, help="List file, URL, or alias")
    parser.add_argument("--output-dir", "-o", default="content/cosmetic_sites")
    parser.add_argument("--dump", metavar="PATH", help="Write the filtered site-specific rules to PATH and exit")
    args = parser.parse_args()

    lines = [line for src in args.input for line in fetch_or_read_file(src)]
    if args.dump:
        kept = sorted({line.strip() for line in lines if parse_cosmetic(line)})
        dump_lines(args.dump, args.input, kept, "site-specific cosmetic rules")
        return
    stats = write_buckets(compile_rules(lines), args.output_dir)
    print(f"Wrote {stats['selectors']} selectors for {stats['hosts']} hosts in {stats['buckets']} buckets to {args.output_dir}")


if __name__ == "__main__":
    main()
